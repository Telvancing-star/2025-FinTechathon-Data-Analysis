import pandas as pd
from datetime import datetime

# 读取数据
df = pd.read_csv('./data/cluster.csv', encoding='gb18030')

# 定义26个轮次及其对应的日期范围
round_definitions = {
    '2019.4': ('2019-04-01', '2019-04-30'),
    '2019.5': ('2019-05-01', '2019-05-31'),
    '2019.7': ('2019-07-01', '2019-07-31'),
    '2019.10': ('2019-10-01', '2019-10-31'),
    '2020.1': ('2020-01-01', '2020-01-31'),
    '2020.2': ('2020-02-01', '2020-02-29'),
    '2020.10': ('2020-10-01', '2020-10-31'),
    '2020.11': ('2020-11-01', '2020-11-30'),
    '2021.1': ('2021-01-01', '2021-01-31'),
    '2021.4': ('2021-04-01', '2021-04-30'),
    '2021.7': ('2021-07-01', '2021-07-31'),
    '2021.10': ('2021-10-01', '2021-10-31'),
    '2022.1': ('2022-01-01', '2022-01-31'),
    '2022.4': ('2022-04-01', '2022-04-30'),
    '2022.7': ('2022-07-01', '2022-07-31'),
    '2022.10': ('2022-10-01', '2022-10-31'),
    '2022.11': ('2022-11-01', '2022-11-30'),
    '2022.12': ('2022-12-01', '2022-12-31'),
    '2023.1': ('2023-01-01', '2023-01-31'),
    '2023.2': ('2023-02-01', '2023-02-28'),
    '2023.4': ('2023-04-01', '2023-04-30'),
    '2023.7': ('2023-07-01', '2023-07-31'),
    '2023.10': ('2023-10-01', '2023-10-31'),
    '2023.11': ('2023-11-01', '2023-11-30'),
    '2023.12': ('2023-12-01', '2023-12-31'),
    '2024.1': ('2024-01-01', '2024-01-31')
}

round_use = {
    i:list(round_definitions.values())[i] for i in range(26)
}

# 转换为datetime格式
df['Journal Date'] = pd.to_datetime(df['Journal Date'], format='%d/%b/%Y')

# 映射函数
def map_to_round(date):
    for round_name, (start_date, end_date) in round_use.items():
        if pd.to_datetime(start_date) <= date <= pd.to_datetime(end_date):
            return round_name
    return 'Unknown'  # 如果没有匹配的轮次

# 应用映射
df['Round'] = df['Journal Date'].apply(map_to_round)

# 保存到新文件
df.to_csv('./data/cluster_with_rounds.csv', index=False, encoding='gb18030')